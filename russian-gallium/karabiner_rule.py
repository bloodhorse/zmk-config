import json, os, sys
from build_page import TWIN, parse

PATH = os.path.expanduser("~/.config/karabiner/karabiner.json")
TAG = "Russian Gallium"

STOCK = dict(zip("йцукенгшщзхъфывапролджэячсмитьбю.",
                 "q w e r t y u i o p open_bracket close_bracket a s d f g h j k l semicolon quote z x c v b n m comma period slash".split()))
STOCK[","] = ("slash", ["left_shift"])
KEY = {";": "semicolon", ",": "comma", ".": "period", "/": "slash", "[": "open_bracket", "]": "close_bracket", "`": "grave_accent_and_tilde"}

CONDITIONS = [
    {"input_sources": [{"language": "^ru$"}], "type": "input_source_if"},
    {"identifiers": [{"product_id": 24926, "vendor_id": 7504}], "type": "device_if"},
    {"name": "gallium_off", "type": "variable_if", "value": 0},
    {"name": "game", "type": "variable_unless", "value": 1},
    {"name": "fuck", "type": "variable_unless", "value": 1},
    {"name": "shit", "type": "variable_unless", "value": 1},
]


def rule():
    manips = []
    for ch, seat in parse(TWIN).items():
        if seat not in KEY and len(seat) != 1:
            continue
        src = KEY.get(seat, seat)
        dst = STOCK[ch]
        key, mods = dst if isinstance(dst, tuple) else (dst, None)
        if key == src and not mods:
            continue
        to = {"key_code": key}
        if mods:
            to["modifiers"] = mods
        manips.append({"conditions": CONDITIONS, "from": {"key_code": src, "modifiers": {"optional": ["shift", "caps_lock"]}},
                       "to": [to], "type": "basic"})
    return {"description": f"{TAG} (Lily58, Russian input): bekh's own Russian layout, each key sent as the stock ЙЦУКЕН key that types its letter. "
                           "Generated by lily58-zmk/russian-gallium/karabiner_rule.py; the layout is docs/russian-gallium.md. "
                           "э is alt+Enter (the alt numpad rule's quote), ъ is ] as in stock, ё has no key. Steps aside for fuck, shit, game and gallium_off.",
            "manipulators": manips}


def main():
    raw = open(PATH).read()
    c = json.loads(raw)
    rules = c["profiles"][0]["complex_modifications"]["rules"]
    rules[:] = [r for r in rules if not r.get("description", "").startswith(TAG)]
    at = next(i for i, r in enumerate(rules) if r.get("description", "").startswith("Gallium mod-combos")) + 1
    new = rule()
    rules.insert(at, new)
    open(PATH, "w").write(json.dumps(c, indent=4, ensure_ascii=False) + "\n")
    print(f"rule at index {at}, {len(new['manipulators'])} keys")


if __name__ == "__main__":
    main()
